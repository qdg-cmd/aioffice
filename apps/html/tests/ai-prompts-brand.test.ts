import { describe, expect, it } from 'vitest'
import { PRODUCT_NAME, UPSTREAM_PRODUCT_NAME } from '@genoffice/i18n'
import { buildBriefWriterRequest } from '../src/renderer/ai/brief-writer'
import { createDocumentSkill } from '../src/renderer/ai/html-skill'
import { buildPageWriterRequest } from '../src/renderer/ai/page-writer'
import type { HtmlDocAccess } from '../src/renderer/ai/tools'
import { BRIEF_META_NAME, type Brief } from '../src/renderer/document/brief'
import { buildParseMap } from '../src/renderer/document/parse-map'

const DOC = '<!doctype html><html><head><title>T</title></head><body><h1>Hello</h1></body></html>'

const access: HtmlDocAccess = {
  getText: () => DOC,
  getVersion: () => 1,
  getMap: () => buildParseMap(DOC, 1, null),
  getLastManualVersion: () => 0,
  getFilePath: () => null,
  getSelectedSid: () => null,
  applyOps: () => ({ ok: true, ranges: [] }),
  replaceAll: () => undefined,
}

const brief = {
  core_hook: 'hook',
  style: {},
  alternatives: [],
  sections: [],
  meta: {},
} as unknown as Brief

/** Every system prompt the editor sends: the chat assistant, the brief writer, both page writers */
const prompts: Record<string, string> = {
  assistant: createDocumentSkill(access).systemPrompt,
  briefWriter: buildBriefWriterRequest({ mode: 'new' }, [], '').system,
  pageWriter: buildPageWriterRequest({ kind: 'design', brief, instruction: 'x' }, '').system,
  documentWriter: buildPageWriterRequest({ kind: 'content', plan: 'p', instruction: 'x' }, '')
    .system,
}

describe('AI system prompts', () => {
  it.each(Object.keys(prompts))('%s names this product, not the upstream one', (name) => {
    const prompt = prompts[name]!
    expect(prompt).toContain(`${PRODUCT_NAME} HTML`)
    expect(prompt).not.toContain(UPSTREAM_PRODUCT_NAME)
  })

  it('never asks the model to put the product or a vendor name into the page', () => {
    for (const prompt of Object.values(prompts)) {
      // the one mention is the model's own role line; nothing tells it to brand the output
      expect(prompt.split(PRODUCT_NAME)).toHaveLength(2)
      expect(prompt).not.toMatch(/powered by|made with|generated by/i)
    }
  })

  it('keeps the identifier stored inside saved pages', () => {
    // the pinned-brief meta is document data shared with pages made by the upstream editor
    expect(BRIEF_META_NAME).toBe('genoffice:brief')
  })
})
